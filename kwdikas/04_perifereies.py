# Ερώτημα 3: πού μετακινήθηκαν οι διανυκτερεύσεις το 2025
#
# Πηγές: ΕΛΣΤΑΤ STO12 δελτίο τύπου 2025 Πίνακας 4, ξενοδοχεία,
#        κάμπινγκ και καταλύματα σύντομης διαμονής
#        ΕΛΣΤΑΤ STO18 πειραματική στατιστική 2025 Πίνακας 5,
#        ψηφιακές πλατφόρμες με πηγή το μητρώο της ΑΑΔΕ
# Παράγει: q3_perifereies.csv
#
# Τα δύο σύνολα ΔΕΝ επικαλύπτονται. Το STO18 γράφει ρητά ότι στόχος
# του είναι «η κάλυψη της τουριστικής κίνησης που δεν περιλαμβάνεται
# στις υφιστάμενες επίσημες στατιστικές». Είναι συμπληρωματικά.
#
# Τι λείπει: τα ιδιόκτητα εξοχικά, που είναι το μεγαλύτερο μέρος των
# ελληνικών διανυκτερεύσεων και δεν καταγράφονται ανά περιφέρεια
# πουθενά. Ό,τι λέγεται εδώ αφορά το πληρωμένο κατάλυμα.

import os
import pandas as pd

EXODOS = "../dedomena"
os.makedirs(EXODOS, exist_ok=True)

# ------------------------------------------------------------
# 1. STO12, διανυκτερεύσεις 2025 και μεταβολή έναντι 2024
# ------------------------------------------------------------

sto12 = [
    ("Αν. Μακεδονία & Θράκη",  4_038_460,   4.8, "ηπειρωτική"),
    ("Κεντρική Μακεδονία",    18_714_412,   3.3, "ηπειρωτική"),
    ("Δυτική Μακεδονία",         368_066,   7.4, "ηπειρωτική"),
    ("Ήπειρος",                3_387_890,  10.8, "ηπειρωτική"),
    ("Θεσσαλία",               4_442_096,   8.7, "ηπειρωτική"),
    ("Στερεά Ελλάδα",          3_249_674,  10.4, "ηπειρωτική"),
    ("Ιόνια νησιά",           20_363_829,  -0.8, "νησιά"),
    ("Δυτική Ελλάδα",          2_494_078,   6.2, "ηπειρωτική"),
    ("Πελοπόννησος",           6_293_497,   6.5, "ηπειρωτική"),
    ("Αττική",                12_794_781,   0.4, "Αττική"),
    ("Βόρειο Αιγαίο",          3_162_269,   6.0, "νησιά"),
    ("Νότιο Αιγαίο",          41_838_969,   0.8, "νησιά"),
    ("Κρήτη",                 35_199_262,   1.9, "νησιά"),
]
p = pd.DataFrame(sto12, columns=["perifereia", "nyxtes_2025", "metavoli",
                                 "omada"])

# Το δελτίο δίνει μόνο το 2025 και τη μεταβολή. Το 2024 είναι δική μας
# ανακατασκευή, οπότε κουβαλάει το σφάλμα στρογγυλοποίησης της μεταβολής.
p["nyxtes_2024"] = (p["nyxtes_2025"] / (1 + p["metavoli"] / 100)).round(0)

# ------------------------------------------------------------
# 2. STO18, ημέρες μίσθωσης σε πλατφόρμες
# ------------------------------------------------------------

sto18 = [
    ("Αν. Μακεδονία & Θράκη",  46_616,   259_185,  50_508,   319_843),
    ("Αττική",                363_891, 2_612_650, 356_759, 2_642_695),
    ("Βόρειο Αιγαίο",          29_033,   101_526,  31_508,   128_797),
    ("Δυτική Ελλάδα",          43_928,    65_960,  46_338,    72_107),
    ("Δυτική Μακεδονία",       13_272,     9_144,  16_708,    14_340),
    ("Ήπειρος",                51_956,    72_696,  56_550,    81_419),
    ("Θεσσαλία",               95_364,   183_510, 101_620,   200_973),
    ("Ιόνια νησιά",            51_697,   669_835,  49_312,   711_781),
    ("Κεντρική Μακεδονία",    265_331,   915_637, 265_320, 1_025_110),
    ("Κρήτη",                  61_250,   900_132,  57_860,   915_716),
    ("Νότιο Αιγαίο",          103_507,   791_759, 101_698,   808_946),
    ("Πελοπόννησος",          124_910,   314_579, 131_160,   334_934),
    ("Στερεά Ελλάδα",          48_877,    63_587,  52_040,    73_686),
]
pl = pd.DataFrame(sto18, columns=["perifereia", "plat_imed_2024",
                                  "plat_allod_2024", "plat_imed_2025",
                                  "plat_allod_2025"])

pl["plat_2024"] = pl["plat_imed_2024"] + pl["plat_allod_2024"]
pl["plat_2025"] = pl["plat_imed_2025"] + pl["plat_allod_2025"]
pl["plat_metavoli_imed"] = (
    100 * (pl["plat_imed_2025"] / pl["plat_imed_2024"] - 1)).round(1)
pl["plat_metavoli_allod"] = (
    100 * (pl["plat_allod_2025"] / pl["plat_allod_2024"] - 1)).round(1)

# ------------------------------------------------------------
# 3. Ένωση
# ------------------------------------------------------------

d = pd.merge(p, pl, on="perifereia")

d["synolo_2024"] = d["nyxtes_2024"] + d["plat_2024"]
d["synolo_2025"] = d["nyxtes_2025"] + d["plat_2025"]
d["synolo_metavoli"] = (100 * (d["synolo_2025"] / d["synolo_2024"] - 1)).round(1)
d["einai_nisi"] = d["omada"] == "νησιά"

# Κατώφλι -0,5% και όχι σκέτο μηδέν. Η Κεντρική Μακεδονία βγάζει
# -0,004%, δηλαδή πτώση έντεκα ημερών σε 265.331. Είναι στατιστικά
# μηδέν και δεν μπαίνει στην ίδια κατηγορία με την Κρήτη.
d["exase_ellines"] = d["plat_metavoli_imed"] < -0.5

# Για να ξεχωρίζει ο θόρυβος μικρού δείγματος: η Δυτική Μακεδονία είναι
# 1,3% της αγοράς και το +25,9% της δεν σημαίνει τίποτα.
d["meridio_agoras_imed"] = (100 * d["plat_imed_2025"]
                            / d["plat_imed_2025"].sum()).round(1)

d = d.sort_values("synolo_metavoli")
d.to_csv(f"{EXODOS}/q3_perifereies.csv", index=False, encoding="utf-8-sig")

# ------------------------------------------------------------
# 4. Έλεγχοι
# ------------------------------------------------------------

print("ΕΛΕΓΧΟΙ")

print("1. Σύνολο STO12 2025:", f"{p['nyxtes_2025'].sum():,}",
      " δημοσιευμένο 156,347,283  διαφορά",
      p["nyxtes_2025"].sum() - 156_347_283)

print("2. Μεταβολή STO12:",
      round(100 * (p["nyxtes_2025"].sum() / p["nyxtes_2024"].sum() - 1), 1),
      "%  δημοσιευμένη +2.2")

print("3. Σύνολο πλατφορμών 2025:", f"{pl['plat_2025'].sum():,}",
      " δημοσιευμένο 8,647,728")
print("   μερίδιο ημεδαπών:",
      round(100 * pl["plat_imed_2025"].sum() / pl["plat_2025"].sum(), 1),
      "%  δημοσιευμένο 15.2")

print("\n4. Κενά:", int(d.isna().sum().sum()))
print("\nτα αρχεία γράφτηκαν στον φάκελο", EXODOS)
