# Ερώτημα 4: πόσο κοστίζει η νύχτα, εντός και εκτός Ελλάδας
#
# Πηγές: ΕΛΣΤΑΤ, δελτίο τύπου STO15 2025, Πίνακες 4, 8 και 11
#        ΙΝΣΕΤΕ, «Η συμβολή του τουρισμού στην ελληνική οικονομία το 2025»,
#        Πίνακας 6, για ανεξάρτητη επαλήθευση
# Παράγει: q4_proorismos.csv, q4_insete.csv
#
# Οι Πίνακες 4, 8 και 11 σπάνε ταξίδια, νύχτες και δαπάνη σε εσωτερικού
# και εξωτερικού. Ο λόγος δαπάνης προς νύχτες δίνει τη Μέση Δαπάνη ανά
# Διανυκτέρευση, το ίδιο μέγεθος που δημοσιεύει το ΙΝΣΕΤΕ.
#
# Όλες οι συγκρίσεις εδώ γίνονται μέσα στην ίδια έρευνα. Η ΤτΕ δίνει
# άλλα νούμερα για το εξωτερικό, επειδή μετράει άλλο πράγμα. Ο έλεγχος 4
# δείχνει πόσο διαφέρουν και γιατί δεν τα αναμειγνύουμε.
#
# Όλα αφορούν προσωπικά ταξίδια ημεδαπών 15 ετών και άνω, με τουλάχιστον
# μία διανυκτέρευση. Τα επαγγελματικά εξαιρούνται από την ΕΛΣΤΑΤ.

import os
import pandas as pd

EXODOS = "../dedomena"
os.makedirs(EXODOS, exist_ok=True)

# ------------------------------------------------------------
# 1. Ταξίδια, νύχτες και δαπάνη ανά προορισμό
# ------------------------------------------------------------
# ταξίδια και νύχτες σε χιλιάδες, δαπάνη σε χιλιάδες ευρώ

etos = [2019, 2020, 2021, 2022, 2023, 2024, 2025]

tax_es = [4_942, 4_332, 4_705, 5_802, 5_751, 5_975, 6_740]
tax_ex = [840, 272, 348, 851, 927, 998, 1_186]

nyx_es = [53_651, 52_729, 55_262, 58_818, 56_440, 60_443, 63_965]
nyx_ex = [7_638, 3_312, 3_760, 8_402, 8_554, 7_810, 9_308]

dap_es = [1_598_637, 1_408_618, 1_719_607, 2_249_270, 2_253_774,
          2_405_654, 2_701_024]
dap_ex = [513_424, 170_153, 208_064, 684_197, 770_235, 845_465, 983_656]

grammes = []
for i in range(len(etos)):
    grammes.append([etos[i], "Εντός Ελλάδας", tax_es[i], nyx_es[i], dap_es[i]])
    grammes.append([etos[i], "Στο εξωτερικό", tax_ex[i], nyx_ex[i], dap_ex[i]])

p = pd.DataFrame(grammes, columns=["etos", "proorismos", "taxidia",
                                   "nyxtes", "dapani"])

# Χιλιάδες ευρώ διά χιλιάδες νύχτες δίνει ευρώ.
p["evrw_ana_nyxta"] = (p["dapani"] / p["nyxtes"]).round(1)
p["evrw_ana_taxidi"] = (p["dapani"] / p["taxidia"]).round(1)
p["nyxtes_ana_taxidi"] = (p["nyxtes"] / p["taxidia"]).round(1)

p.to_csv(f"{EXODOS}/q4_proorismos.csv", index=False, encoding="utf-8-sig")

# ------------------------------------------------------------
# 2. Οι τρεις δείκτες του ΙΝΣΕΤΕ για τον εγχώριο τουρισμό
# ------------------------------------------------------------
# Το ΙΝΣΕΤΕ δημοσιεύει ΜΔΔ, ΜΚΔ και ΜΔΠ μόνο για τα ταξίδια εσωτερικού
# και μόνο μέχρι το 2024. Τα ξαναϋπολογίζουμε από τα πρωτογενή για να
# δούμε αν βγαίνουν ίδια, και τα επεκτείνουμε στο 2025.

eg = p[p["proorismos"] == "Εντός Ελλάδας"].copy()
eg = eg[["etos", "evrw_ana_nyxta", "evrw_ana_taxidi", "nyxtes_ana_taxidi"]]
eg.columns = ["etos", "mdd", "mkd", "mdp"]

# Δημοσιευμένα ΙΝΣΕΤΕ, Πίνακας 6. Κενό όπου δεν δημοσιεύουν.
insete_mdd = {2019: 30, 2020: 27, 2021: 31, 2022: 38, 2023: 40, 2024: 40}
insete_mkd = {2019: 324, 2020: 325, 2021: 365, 2022: 388, 2023: 392,
              2024: 403}
insete_mdp = {2019: 10.9, 2020: 12.2, 2021: 11.7, 2022: 10.1, 2023: 9.8,
              2024: 10.1}

eg["mdd_insete"] = eg["etos"].map(insete_mdd)
eg["mkd_insete"] = eg["etos"].map(insete_mkd)
eg["mdp_insete"] = eg["etos"].map(insete_mdp)

eg.to_csv(f"{EXODOS}/q4_insete.csv", index=False, encoding="utf-8-sig")

# ------------------------------------------------------------
# 3. Έλεγχοι
# ------------------------------------------------------------

print("ΕΛΕΓΧΟΙ")

x24 = eg[eg["etos"] == 2024]
print("1. Οι τρεις δείκτες του 2024 έναντι των δημοσιευμένων ΙΝΣΕΤΕ")
print("   ΜΔΔ", x24["mdd"].values[0], "έναντι", x24["mdd_insete"].values[0])
print("   ΜΚΔ", x24["mkd"].values[0], "έναντι", x24["mkd_insete"].values[0])
print("   ΜΔΠ", x24["mdp"].values[0], "έναντι", x24["mdp_insete"].values[0])

# Το ΙΝΣΕΤΕ στρογγυλοποιεί τη ΜΔΔ και τη ΜΚΔ στην ακέραιη μονάδα.
eg["apoklisi_mdd"] = (eg["mdd"] - eg["mdd_insete"]).abs()
eg["apoklisi_mkd"] = (eg["mkd"] - eg["mkd_insete"]).abs()
print("2. Μέγιστη απόκλιση σε όλα τα έτη με δημοσιευμένο νούμερο")
print("   ΜΔΔ", round(eg["apoklisi_mdd"].max(), 2), " ΜΚΔ",
      round(eg["apoklisi_mkd"].max(), 2), " όριο 1,0")

print("3. Το άθροισμα εσωτερικού και εξωτερικού δίνει τα σύνολα του Πίνακα 11")
for e, syn in [(2024, 3_251_118), (2025, 3_684_680)]:
    d = p[p["etos"] == e]["dapani"].sum()
    print("   ", e, d, "έναντι", syn, " διαφορά", d - syn)

# Η ΤτΕ μετράει κάθε αναχώρηση κατοίκου, ανεξαρτήτως σκοπού και ηλικίας.
# Η ΕΛΣΤΑΤ μόνο προσωπικά ταξίδια, 15 ετών και άνω, με διανυκτέρευση.
print("4. Το εξωτερικό στην ΕΛΣΤΑΤ έναντι της Έρευνας Συνόρων της ΤτΕ, 2025")
ex25 = p[(p["etos"] == 2025) & (p["proorismos"] == "Στο εξωτερικό")]
print("   ταξίδια", ex25["taxidia"].values[0], "χιλ. έναντι 7.200 χιλ.")
print("   νύχτες ", ex25["nyxtes"].values[0], "χιλ. έναντι 35.500 χιλ.")
print("   νύχτες ανά ταξίδι", ex25["nyxtes_ana_taxidi"].values[0],
      "έναντι 4,9")
print("   δεν αναμειγνύονται, μετράνε άλλο πληθυσμό ταξιδιών")

print("5. Το κύριο εύρημα, ευρώ ανά νύχτα το 2025")
for pr in ["Εντός Ελλάδας", "Στο εξωτερικό"]:
    x = p[(p["etos"] == 2025) & (p["proorismos"] == pr)]
    print("   ", pr, x["evrw_ana_nyxta"].values[0], "€")

print("\nτα αρχεία γράφτηκαν στον φάκελο", EXODOS)
