print("ΕΛΕΓΧΟΙ")

print("1. Αθροίσματα ζωνών έναντι δημοσιευμένων συνόλων 2025")
print("   ταξίδια", f"{z['tax25'].sum():,}", "έναντι 7,926   διαφορά",
      z["tax25"].sum() - 7_926)
print("   νύχτες ", f"{z['nyx25'].sum():,}", "έναντι 73,273  διαφορά",
      z["nyx25"].sum() - 73_273)
print("   δαπάνες", f"{z['dap25'].sum():,}", "έναντι 3,684,680  διαφορά",
      z["dap25"].sum() - 3_684_680)

syn_t = [5_781, 4_604, 5_053, 6_653, 6_679, 6_973, 7_926]
