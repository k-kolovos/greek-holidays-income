lathi = 0
for i in range(len(etos)):
    if abs(tax_es[i] + tax_ex[i] - syn_t[i]) > 2:
        lathi = lathi + 1
    if abs(nyx_es[i] + nyx_ex[i] - syn_n[i]) > 2:
        lathi = lathi + 1
print("2. Αθροίσματα προορισμών εκτός ορίου:", lathi, "από 14")

print("\n3. Οι πίτες μεταφοράς ταιριάζουν με τον Πίνακα 4;")
for y, i in [(2024, -2), (2025, -1)]:
    for p, seira_tax in [("Εντός Ελλάδας", tax_es), ("Στο εξωτερικό", tax_ex)]:
        s = mm[(mm["etos"] == y) & (mm["proorismos"] == p)]["synolo"].iloc[0]
        print(f"   {y} {p}: {s:,} έναντι {seira_tax[i]:,}",
              "ναι" if s == seira_tax[i] else "ΟΧΙ")

print("\nτα αρχεία γράφτηκαν στον φάκελο", EXODOS)
