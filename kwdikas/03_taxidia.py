# Όλα αφορούν προσωπικά ταξίδια ημεδαπών 15 ετών και άνω.

import os
import pandas as pd

EXODOS = "../dedomena"
os.makedirs(EXODOS, exist_ok=True)

# ------------------------------------------------------------
# 1. Ζώνες διάρκειας, το κύριο εύρημα
# ------------------------------------------------------------
# ταξίδια και νύχτες σε χιλιάδες, δαπάνες σε χιλιάδες ευρώ

zwnes = [
    # ζώνη, ταξίδια 24, ταξίδια 25, νύχτες 24, νύχτες 25, δαπάνη 24, δαπάνη 25
    ("1 έως 3 νύχτες",  1_669, 2_114,  4_066,  5_197,   455_516,   553_766),
    ("4 έως 7 νύχτες",  3_000, 3_293, 16_007, 17_517, 1_392_949, 1_585_274),
    ("8 έως 14 νύχτες", 1_108, 1_305, 11_354, 13_402,   629_216,   765_468),
    ("15 και άνω",      1_196, 1_215, 36_827, 37_157,   773_438,   780_172),
]
z = pd.DataFrame(zwnes, columns=["zwni", "tax24", "tax25", "nyx24", "nyx25",
                                 "dap24", "dap25"])

# Χωρίς αυτό το Tableau ταξινομεί τις ζώνες αλφαβητικά.
z["seira"] = [1, 2, 3, 4]

# Τα τρία μερίδια δεν συμπίπτουν, και αυτό είναι το εύρημα.
z["mer_taxidia"] = (100 * z["tax25"] / z["tax25"].sum()).round(1)
z["mer_nyxtes"] = (100 * z["nyx25"] / z["nyx25"].sum()).round(1)
z["mer_dapanes"] = (100 * z["dap25"] / z["dap25"].sum()).round(1)

# Χιλιάδες ευρώ διά χιλιάδες νύχτες δίνει ευρώ.
z["evrw_ana_nyxta"] = (z["dap25"] / z["nyx25"]).round(1)
z["nyxtes_ana_taxidi"] = (z["nyx25"] / z["tax25"]).round(1)

# Η μετατόπιση 2024 προς 2025. Το mer_taxidia είναι του 2025.
z["mer_taxidia_2024"] = (100 * z["tax24"] / z["tax24"].sum()).round(1)
z["monades_taxidia"] = (z["mer_taxidia"] - z["mer_taxidia_2024"]).round(1)

z.to_csv(f"{EXODOS}/q2b_asymmetria.csv", index=False, encoding="utf-8-sig")

# ------------------------------------------------------------
# 2. Εσωτερικό έναντι εξωτερικού, επτά χρονιές
# ------------------------------------------------------------

etos = [2019, 2020, 2021, 2022, 2023, 2024, 2025]
tax_es = [4_942, 4_332, 4_705, 5_802, 5_751, 5_975, 6_740]
tax_ex = [840, 272, 348, 851, 927, 998, 1_186]
nyx_es = [53_651, 52_729, 55_262, 58_818, 56_440, 60_443, 63_965]
nyx_ex = [7_638, 3_312, 3_760, 8_402, 8_554, 7_810, 9_308]

grammes = []
for i in range(len(etos)):
    grammes.append([etos[i], "Εντός Ελλάδας", tax_es[i], nyx_es[i]])
    grammes.append([etos[i], "Στο εξωτερικό", tax_ex[i], nyx_ex[i]])

d = pd.DataFrame(grammes, columns=["etos", "proorismos", "taxidia", "nyxtes"])
d["pandimia"] = d["etos"].isin([2020, 2021])

# Οι δύο σειρές είναι ανεξάρτητες, κάθε ρυθμός μετριέται πάνω στη δική
# του προηγούμενη χρονιά. Το υπολογίζουμε εδώ και όχι με Quick Table
# Calculation, γιατί το Tableau μπερδεύει την κατεύθυνση όταν υπάρχουν
# πάνελ και βγάζει λάθος χωρίς να το πει.
d = d.sort_values(["proorismos", "etos"])
d["metavoli"] = (100 * d.groupby("proorismos")["taxidia"].pct_change()).round(1)

d.to_csv(f"{EXODOS}/q2b_proorismos.csv", index=False, encoding="utf-8-sig")

# ------------------------------------------------------------
# 3. Μέσο μεταφοράς, χωριστά ανά προορισμό
# ------------------------------------------------------------
# Από τα Γραφήματα 6 των δελτίων. Είναι πίτες, οπότε έχουμε μόνο
# ποσοστά. Τα απόλυτα βγαίνουν με πολλαπλασιασμό επί τα σύνολα του
# Πίνακα 4, και ο έλεγχος 4 επαληθεύει ότι ταιριάζουν.
#
# Ο συγκεντρωτικός πίνακας μέσων μεταφοράς ανακατεύει εσωτερικό και
# εξωτερικό και δίνει «εναέρια 17,2%», που είναι κυρίως πτήσεις εκτός.
# Δεν χρησιμοποιείται πουθενά.

mm = pd.DataFrame([
    (2024, "Εντός Ελλάδας", "Χερσαία",    74.9, 5_975),
    (2024, "Εντός Ελλάδας", "Θαλάσσια",   19.1, 5_975),
    (2024, "Εντός Ελλάδας", "Αεροπορικά",  6.0, 5_975),
    (2024, "Στο εξωτερικό", "Χερσαία",    21.7,   998),
    (2024, "Στο εξωτερικό", "Θαλάσσια",    1.1,   998),
    (2024, "Στο εξωτερικό", "Αεροπορικά", 77.2,   998),
    (2025, "Εντός Ελλάδας", "Χερσαία",    74.8, 6_740),
    (2025, "Εντός Ελλάδας", "Θαλάσσια",   18.5, 6_740),
    (2025, "Εντός Ελλάδας", "Αεροπορικά",  6.7, 6_740),
    (2025, "Στο εξωτερικό", "Χερσαία",    20.5, 1_186),
    (2025, "Στο εξωτερικό", "Θαλάσσια",    2.6, 1_186),
    (2025, "Στο εξωτερικό", "Αεροπορικά", 76.9, 1_186),
], columns=["etos", "proorismos", "meso", "pososto", "synolo"])

mm["taxidia"] = (mm["synolo"] * mm["pososto"] / 100).round(0)

# Όποιος πάει νησί μπαίνει σε πλοίο ή αεροπλάνο. Εξαιρέσεις η Εύβοια,
# η Λευκάδα, και οι λίγες πτήσεις σε ηπειρωτικούς προορισμούς.
mm["thelei_nisi"] = mm["meso"].isin(["Θαλάσσια", "Αεροπορικά"])

mm.to_csv(f"{EXODOS}/q2b_meso.csv", index=False, encoding="utf-8-sig")

# ------------------------------------------------------------
